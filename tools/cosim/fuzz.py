#!/usr/bin/env python3
"""Constrained-random TFX program fuzzer.

Generates structurally valid programs (balanced if/else/endif, bounded
warp-uniform loops, barriers only at top level) that mix every instruction
class: ALU (R/I), MUL, S2R, LUI, loads from a shared read-only table, loads and
stores to a per-thread private region, ATOM.ADD on shared counters, nested
divergence, loops and BAR. Programs are race-free by construction, so the C++
functional model, the C++ cycle model and the RTL must agree on *all* final
state, and RTL vs cycle model must additionally agree on every counter and on
the full per-cycle issue trace.

  python3 tools/cosim/fuzz.py --config architecture/configuration/tfx_base.json --count 50 --seed 1
"""
from __future__ import annotations

import argparse
import random
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import cosim  # noqa: E402

R_OPS = ["add", "sub", "and", "or", "xor", "sll", "srl", "sra", "slt", "sltu", "seq"]
I_OPS = ["addi", "subi", "andi", "ori", "xori", "slli", "srli", "srai", "slti", "sltui", "seqi"]
M_OPS = ["mul", "mulhu", "mulh"]
MI_OPS = ["muli", "mulhui", "mulhi"]
SREGS = ["lane_id", "warp_id", "global_tid", "num_lanes", "num_warps", "arg0", "arg1", "arg2", "arg3"]
DATA = [f"r{i}" for i in range(3, 16)]
RO_WORDS, ATOM_BASE_W, PRIV_BASE_W, PRIV_WORDS = 64, 64, 128, 8


class Gen:
    def __init__(self, rng: random.Random, cfg: dict, budget: int):
        self.r, self.cfg, self.budget = rng, cfg, budget
        self.lines: list[str] = []
        self.words = 0
        self.labels = 0
        self.max_depth = min(3, cfg["stack_depth"] - 1)

    def emit(self, s: str, w: int = 1):
        self.lines.append("        " + s)
        self.words += w

    def reg(self):
        return self.r.choice(DATA)

    def imm(self):
        return self.r.choice([0, 1, -1, 2, 3, 7, 31, 32, 255, -256, 0x7FFF, -0x8000, self.r.randrange(-2000, 2000)])

    def simple(self):
        k = self.r.random()
        r = self.r
        if k < 0.30:
            self.emit(f"{r.choice(R_OPS)} {self.reg()}, {self.reg()}, {self.reg()}")
        elif k < 0.50:
            self.emit(f"{r.choice(I_OPS)} {self.reg()}, {self.reg()}, {self.imm()}")
        elif k < 0.60:
            self.emit(f"{r.choice(M_OPS)} {self.reg()}, {self.reg()}, {self.reg()}")
        elif k < 0.65:
            self.emit(f"{r.choice(MI_OPS)} {self.reg()}, {self.reg()}, {self.imm()}")
        elif k < 0.70:
            self.emit(f"s2r {self.reg()}, {r.choice(SREGS)}")
        elif k < 0.73:
            self.emit(f"lui {self.reg()}, {r.randrange(0, 0x10000)}")
        elif k < 0.76:
            self.emit(f"mov {self.reg()}, {self.reg()}")
        elif k < 0.84:   # shared read-only table
            self.emit(f"andi r16, {self.reg()}, {RO_WORDS - 1}")
            self.emit("slli r16, r16, 2")
            self.emit(f"lw {self.reg()}, 0(r16)")
        elif k < 0.92:   # private region store / load
            self.emit(f"andi r16, {self.reg()}, {PRIV_WORDS - 1}")
            self.emit("slli r16, r16, 2")
            self.emit("add r16, r16, r2")
            if r.random() < 0.6:
                self.emit(f"sw {self.reg()}, 0(r16)")
            else:
                self.emit(f"lw {self.reg()}, 0(r16)")
        else:            # atomic on a shared counter; old value discarded (order-independent state)
            self.emit(f"andi r16, {self.reg()}, 3")
            self.emit("slli r16, r16, 2")
            self.emit(f"addi r16, r16, {ATOM_BASE_W * 4}")
            self.emit(f"atom.add r0, r16, {self.reg()}")

    def block(self, depth: int, n: int, top: bool):
        for _ in range(n):
            if self.words > self.budget:
                return
            k = self.r.random()
            if k < 0.12 and depth < self.max_depth:
                self.emit(f"andi r17, {self.reg()}, {self.r.choice([1, 2, 3, 5, 0xFF])}")
                self.emit("if r17")
                self.block(depth + 1, self.r.randrange(1, 5), False)
                if self.r.random() < 0.5:
                    self.emit("else")
                    self.block(depth + 1, self.r.randrange(1, 4), False)
                self.emit("endif")
            elif k < 0.18 and depth < self.max_depth:
                cnt = f"r{20 + depth}"
                lab = f"L{self.labels}"
                self.labels += 1
                self.emit(f"movi {cnt}, {self.r.randrange(1, 4)}")
                self.lines.append(f"{lab}:")
                self.block(depth + 1, self.r.randrange(1, 4), False)
                self.emit(f"subi {cnt}, {cnt}, 1")
                self.emit(f"bany {cnt}, {lab}")
            elif k < 0.21 and top:
                self.emit("bar")
            else:
                self.simple()

    def program(self) -> str:
        self.lines = ["; generated by tools/cosim/fuzz.py"]
        self.emit("s2r r1, global_tid")
        self.emit("slli r2, r1, 5")                       # tid * PRIV_WORDS * 4
        self.emit(f"addi r2, r2, {PRIV_BASE_W * 4}")
        for rr in DATA:
            if self.r.random() < 0.7:
                v = self.r.getrandbits(32)
                self.emit(f"li {rr}, {v}", 2)
        self.block(0, 200, True)
        self.emit("exit")
        return "\n".join(self.lines) + "\n"


def make_job(rng: random.Random, cfg: dict, idx: int) -> cosim.Job:
    budget = min(cfg["imem_depth"], 256) - 40
    while True:
        g = Gen(rng, cfg, budget)
        src = g.program()
        words, _l, syms = cosim.tfxasm.assemble(src)
        if len(words) <= cfg["imem_depth"]:
            break
    mem = {i: rng.getrandbits(32) for i in range(RO_WORDS)}
    mem |= {ATOM_BASE_W + i: rng.getrandbits(8) for i in range(4)}
    warps = rng.randrange(1, cfg["num_warps"] + 1)
    for t in range(warps * cfg["num_lanes"]):
        for k in range(PRIV_WORDS):
            mem[PRIV_BASE_W + t * PRIV_WORDS + k] = rng.getrandbits(32) if rng.random() < 0.3 else 0
    args = {i: rng.getrandbits(32) for i in range(4)}
    policy = rng.choice(list(cosim.POLICIES))
    job = cosim.Job(name=f"fuzz{idx}", words=words, mem=mem, args=args, warps=warps, policy=policy, symbols=syms)
    job.source = src
    return job


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", required=True)
    ap.add_argument("--count", type=int, default=20)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--no-rtl", action="store_true", help="only cross-check the two C++ models")
    ap.add_argument("--save-failures", default=str(cosim.BUILD / "fuzz_failures"))
    a = ap.parse_args(argv)
    cfg = cosim.load_config(a.config)
    rng = random.Random(a.seed)
    fails, cycles, t0 = 0, 0, time.time()
    for i in range(a.count):
        job = make_job(rng, cfg, i)
        rep = cosim.cosim(job, cfg, seed=a.seed * 1000 + i, rtl=not a.no_rtl, func_regs=True)
        cycles += rep["cpp"]["perf"][0]
        if not rep["ok"]:
            fails += 1
            d = Path(a.save_failures)
            d.mkdir(parents=True, exist_ok=True)
            (d / f"{cfg['name']}_s{a.seed}_{i}.tfx").write_text(job.source)
            print(f"FAIL #{i} (policy={job.policy}, warps={job.warps}):")
            for m in rep["mismatches"][:4]:
                print("   ", m)
    print(f"fuzz {cfg['name']} seed={a.seed}: {a.count - fails}/{a.count} programs agree "
          f"({'C++ func + C++ timing + RTL' if not a.no_rtl else 'C++ func + C++ timing'}), "
          f"{cycles} simulated cycles, {time.time() - t0:.1f}s")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
